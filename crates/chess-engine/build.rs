//! Build script – embeds the NNUE network and generates the LMR (late move reductions) table.
//!
//! LMR formula taken from tinychess (`gen-lmr-red-table.py`, mul = 0.65, base = 1.0):
//! `reduction = ln(depth) · ln(move_number + 1) · 0.65 + 1` (0 for depth 0).
//! A microcontroller should not compute logarithms, so the table is prepared in advance.

use std::env;
use std::fmt::Write;
use std::fs;
use std::path::PathBuf;

const N: usize = 64;
const MUL: f64 = 0.65;
const BASE: f64 = 1.0;

/// Selects the network (NNUE_NET, otherwise the default net), validates its format
/// and generates `net_config.rs` with the architecture constants and embedded weights.
fn gen_net_config() {
    println!("cargo:rerun-if-env-changed=NNUE_NET");
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let path = match env::var("NNUE_NET") {
        Ok(p) if !p.is_empty() => PathBuf::from(p),
        // default: 768→128 with i8 weights (QA=127) and 8 output buckets
        _ => manifest.join("nets/h128-v4-i8.bin"),
    };
    let path =
        fs::canonicalize(&path).unwrap_or_else(|e| panic!("NNUE network {}: {e}", path.display()));
    println!("cargo:rerun-if-changed={}", path.display());
    let bytes = fs::read(&path).unwrap();
    let a = nnue_core::Arch::detect(&bytes)
        .unwrap_or_else(|e| panic!("invalid network {}: {e:?}", path.display()));
    let arch = if a.legacy {
        format!("nnue_core::Arch::legacy({})", a.hidden)
    } else {
        format!(
            "nnue_core::Arch {{ small_out: {}, ..nnue_core::Arch::from_header(&nnue_core::Header {{ \
             hidden: {}, out_buckets: {}, l1: {}, l2: {}, ft_type: nnue_core::FtType::{:?}, \
             qa: {}, qb: {}, qh: {}, scale: {} }}) }}",
            a.small_out, a.hidden, a.out_buckets, a.l1, a.l2, a.ft_type, a.qa, a.qb, a.qh, a.scale
        )
    };
    let code = format!(
        "/// Number of FT hidden neurons (depends on the selected network).\n\
         pub const HIDDEN: usize = {h};\n\
         /// Network file name (for printouts, e.g. the benchmark).\n\
         pub const NET_FILE: &str = {file:?};\n\
         /// Network file length in bytes.\n\
         pub const NET_LEN: usize = {len};\n\
         /// Architecture (generated by build.rs from {file}).\n\
         pub const ARCH: nnue_core::Arch = {arch};\n\
         static NET_DATA: &Aligned<[u8; NET_LEN]> = &Aligned(*include_bytes!({path:?}));\n",
        h = a.hidden,
        len = bytes.len(),
        file = path.file_name().unwrap().to_string_lossy().to_string(),
        path = path.display().to_string(),
    );
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("net_config.rs");
    fs::write(out, code).unwrap();
}

fn main() {
    gen_net_config();
    let mut code = String::new();
    code.push_str("/// LMR reduction table [depth][move number] (generated by build.rs).\n");
    writeln!(code, "pub static LMR_REDUCTIONS: [[u8; {N}]; {N}] = [").unwrap();
    for depth in 0..N {
        code.push_str("    [");
        for played in 0..N {
            let value = if depth == 0 {
                0
            } else {
                ((depth as f64).ln() * ((played + 1) as f64).ln() * MUL + BASE) as u8
            };
            write!(code, "{value},").unwrap();
        }
        code.push_str("],\n");
    }
    code.push_str("];\n");

    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("lmr_table.rs");
    fs::write(out, code).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}
