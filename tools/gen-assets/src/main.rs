//! Converts the SVG chess pieces (web/pieces/*.svg) into bitmaps for the board's display.
//!
//! Run from the project root:
//! ```text
//! cargo run -p gen-assets
//! ```
//! Generates `crates/chess-display/src/pieces_data.rs` (the file is committed,
//! so the firmware build does not need this tool).
//!
//! Each pixel is stored in 2 bits: 0 = transparent, 1 = outline (black),
//! 2 = fill (white), 3 = half-tone (dark grey – anti-aliased edges).

use std::fmt::Write;
use std::fs;
use std::path::Path;

use resvg::{tiny_skia, usvg};

const PIECES: [&str; 12] = [
    "wP", "wN", "wB", "wR", "wQ", "wK", "bP", "bN", "bB", "bR", "bQ", "bK",
];
const SIZES: [u32; 3] = [25, 12, 10];

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut code = String::new();
    code.push_str("//! GENERATED by `tools/gen-assets` – do not edit by hand.\n");
    code.push_str(
        "//! Piece bitmaps (2 bits per pixel, row by row, most significant bit first).\n",
    );
    code.push_str(
        "//! Order: white P N B R Q K, black P N B R Q K. Source: cburnett set (CC BY-SA 3.0).\n\n",
    );

    for size in SIZES {
        let bytes_per_piece = (size * size * 2).div_ceil(8) as usize;
        writeln!(
            code,
            "pub const PIECE_{size}_BYTES: usize = {bytes_per_piece};"
        )
        .unwrap();
        writeln!(
            code,
            "pub static PIECES_{size}: [[u8; {bytes_per_piece}]; 12] = ["
        )
        .unwrap();
        for name in PIECES {
            let svg =
                fs::read(root.join("web/pieces").join(format!("{name}.svg"))).expect("piece SVG");
            let levels = rasterize(&svg, size);
            let packed = pack(&levels);
            assert_eq!(packed.len(), bytes_per_piece);
            write!(code, "    // {name}\n    [").unwrap();
            for (i, byte) in packed.iter().enumerate() {
                if i % 20 == 0 {
                    code.push_str("\n        ");
                }
                write!(code, "0x{byte:02x},").unwrap();
            }
            code.push_str("\n    ],\n");
            if size == 25 {
                preview(name, &levels, size);
            }
        }
        code.push_str("];\n\n");
    }

    let out = root.join("crates/chess-display/src/pieces_data.rs");
    fs::write(&out, code).unwrap();
    println!("Written: {}", out.display());
}

/// Renders the SVG at `size`×`size` and classifies each pixel into one of 4 levels.
fn rasterize(svg: &[u8], size: u32) -> Vec<u8> {
    let tree = usvg::Tree::from_data(svg, &usvg::Options::default()).expect("valid SVG");
    let mut pixmap = tiny_skia::Pixmap::new(size, size).unwrap();
    let scale = size as f32 / tree.size().width();
    resvg::render(
        &tree,
        tiny_skia::Transform::from_scale(scale, scale),
        &mut pixmap.as_mut(),
    );

    pixmap
        .pixels()
        .iter()
        .map(|p| {
            let c = p.demultiply();
            let alpha = c.alpha() as u32;
            let light = (c.red() as u32 * 3 + c.green() as u32 * 6 + c.blue() as u32) / 10;
            if alpha < 90 {
                0 // transparent
            } else if light > 170 {
                2 // white fill
            } else if light < 70 || alpha > 200 {
                1 // black outline
            } else {
                3 // half-tone (edge)
            }
        })
        .collect()
}

/// Packs the levels 4 pixels per byte (first pixel in the most significant bits).
fn pack(levels: &[u8]) -> Vec<u8> {
    levels
        .chunks(4)
        .map(|chunk| {
            chunk
                .iter()
                .enumerate()
                .fold(0u8, |byte, (i, &v)| byte | (v << (6 - 2 * i)))
        })
        .collect()
}

/// Console preview (for a visual check).
fn preview(name: &str, levels: &[u8], size: u32) {
    println!("{name}:");
    for row in levels.chunks(size as usize) {
        let line: String = row
            .iter()
            .map(|&v| [' ', '#', '.', '+'][v as usize])
            .collect();
        println!("  |{line}|");
    }
}
